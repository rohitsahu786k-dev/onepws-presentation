function defaultExperience(chapter: Chapter): ChapterExperienceMetadata {
  const mapped = experienceByChapterId[chapter.id];
  const isPeak = mapped?.intensity === "peak";
  const isInteractive =
    mapped?.interactionType !== "passive" && mapped?.interactionType !== "guided-continue";

  return {
    energyLevel: isPeak ? 5 : mapped?.intensity === "high" ? 4 : 3,
    informationDensity: chapter.technicalLayers.length >= 3 ? 4 : 3,
    interactionLevel: isInteractive ? 3 : 1,
    visualIntensity: isPeak ? 5 : mapped?.intensity === "high" ? 4 : 3,
    recommendedDurationMs: chapter.durationMs,
    narrationRecommended: Boolean(chapter.media?.narrationAssetId) || isPeak,
    userInputExpected: isInteractive,
    memoryMoment:
      isPeak || ["human-centred-philosophy", "incident-response", "project-portfolio"].includes(chapter.id),
    skippableInAutoplay: false,
    optionalInPresenterMode: chapter.chapterPurpose === "proof",
  };
}

